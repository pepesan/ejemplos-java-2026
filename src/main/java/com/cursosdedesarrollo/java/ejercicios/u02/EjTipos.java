// Ejercicio u02-1: variables y tipos básicos.
public class EjTipos {

    public static int     duplicar(int n)  { return n * 2; }
    public static double  mitad(double d)  { return d / 2; }
    public static boolean esPar(int n)     { return n % 2 == 0; }
}
